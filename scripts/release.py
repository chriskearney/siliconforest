"""Assemble candidate artifacts; emit an install bootstrap only for a qualified set."""
import argparse
import json
from pathlib import Path
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from installer.release import digest, validate, verify_packages, require, verify_database
from package import installer_archive

ROOT_VERIFIER = '''import hashlib, os, pathlib, subprocess, sys, tempfile
os.environ['PATH'] = '/usr/sbin:/usr/bin:/sbin:/bin'
with tempfile.TemporaryDirectory(prefix='siliconforest-root-', dir='/var/tmp') as temporary:
    payload = pathlib.Path(sys.argv[1]).read_bytes()
    if hashlib.sha256(payload).hexdigest() != sys.argv[2]:
        raise SystemExit('SiliconForest installer hash changed before elevation')
    protected = pathlib.Path(temporary) / 'installer.pyz'
    protected.write_bytes(payload)
    protected.chmod(0o700)
    arguments = ['--release', sys.argv[3], '--fingerprint', sys.argv[4], '--install']
    if sys.argv[5]:
        arguments.append(sys.argv[5])
    subprocess.run([sys.executable, '-I', str(protected), *arguments], check=True)
'''


def bootstrap(tag, fingerprint, sha, catalog=False):
    return '''#!/usr/bin/env bash
# Generated from a qualified, immutable SiliconForest release.
set -euo pipefail
tag=''' + tag + '''
fingerprint=''' + fingerprint + '''
expected=''' + sha + '''
selector=''' + ('--catalog' if catalog else "''") + '''
work=$(mktemp -d)
trap 'rm -rf -- "$work"' EXIT
curl --fail --silent --show-error --location --proto '=https' --proto-redir '=https' \\
  "https://github.com/iconidentify/siliconforest/releases/download/$tag/siliconforest.pyz" -o "$work/installer.pyz"
printf '%s  %s\\n' "$expected" "$work/installer.pyz" | sha256sum --check --status
case ${1:---install} in
  --check) python3 "$work/installer.pyz" --check ;;
  --dry-run) python3 "$work/installer.pyz" ${selector:+"$selector"} --release "$tag" --fingerprint "$fingerprint" --dry-run ;;
  --install)
    python3 "$work/installer.pyz" ${selector:+"$selector"} --release "$tag" --fingerprint "$fingerprint" --dry-run
    sudo /usr/bin/python3 -I - "$work/installer.pyz" "$expected" "$tag" "$fingerprint" "$selector" <<'SF_ROOT_VERIFY'
''' + ROOT_VERIFIER + '''SF_ROOT_VERIFY
    ;;
  *) echo 'Usage: install.sh [--check|--dry-run|--install]' >&2; exit 2 ;;
esac
'''


def main():
    p = argparse.ArgumentParser(description=__doc__)
    kind = p.add_mutually_exclusive_group(required=True)
    kind.add_argument('--manifest', type=Path)
    kind.add_argument('--catalog', type=Path, help='signed board/firmware index of qualified release tags')
    p.add_argument('--packages', type=Path)
    p.add_argument('--output', required=True, type=Path)
    p.add_argument('--signing-key', help='existing owner key; never generated by this tool')
    a = p.parse_args()
    if a.catalog:
        from installer.release import asset_name
        index = json.loads(a.catalog.read_text())
        require(index['schema'] == 1 and index['releases'], 'Require a nonempty catalog')
        asset_name(index['id'])
        seen = set()
        for child in index['releases']:
            asset_name(child['release'])
            require(child['release'] != index['id'], 'Catalog cannot select itself')
            for board in child['boards']:
                for firmware in child['firmware']:
                    require((board, firmware) not in seen, 'Ambiguous board/firmware catalog')
                    seen.add((board, firmware))
        require(a.signing_key and len(a.signing_key) in (40, 64) and
                all(c in '0123456789ABCDEF' for c in a.signing_key), 'Signing identity required for a catalog')
        require(not a.output.exists(), 'Use a fresh output directory')
        a.output.mkdir(parents=True)
        target = a.output / 'catalog.json'
        target.write_text(json.dumps(index, indent=2) + '\n')
        subprocess.run(['gpg', '--batch', '--yes', '--local-user', a.signing_key,
                        '--detach-sign', str(target)], check=True)
        (a.output / 'release-key.asc').write_bytes(subprocess.check_output(
            ['gpg', '--armor', '--export', a.signing_key]))
        installer_archive(a.output / 'siliconforest.pyz')
        (a.output / 'install.sh').write_text(bootstrap(index['id'], a.signing_key,
            digest(a.output / 'siliconforest.pyz'), catalog=True))
        print('Catalog bootstrap assembled. Each selected child must still pass signature and qualification checks.')
        return
    require(a.packages, '--packages is required with --manifest')
    data = json.loads(a.manifest.read_text())
    # Validate both the candidate contract and, when signing, its hardware results.
    validate(data, install=bool(a.signing_key))
    require(not a.output.exists(), 'Use a fresh release output directory')
    require(not a.signing_key or (len(a.signing_key) in (40, 64) and
            all(c in '0123456789ABCDEF' for c in a.signing_key)), 'Require a full signing fingerprint')
    a.output.mkdir(parents=True)
    for package in data['packages'].values():
        source = a.packages / package['file']
        require(digest(source) == package['sha256'], 'Candidate package differs from manifest')
        shutil.copy2(source, a.output / source.name)
    verify_packages(a.output, data)
    names = [p['file'] for p in data['packages'].values()]
    if a.signing_key:
        for name in names:
            subprocess.run(['gpg', '--batch', '--yes', '--local-user', a.signing_key,
                '--detach-sign', str(a.output / name)], check=True)
    database = a.output / 'siliconforest.db.tar.gz'
    command = ['repo-add']
    if a.signing_key:
        command += ['--sign', '--key', a.signing_key]
    subprocess.run(command + [str(database), *[str(a.output / n) for n in names]], check=True)
    # GitHub release assets are regular files, not repo-add's convenience symlinks.
    short = a.output / 'siliconforest.db'
    short.unlink(missing_ok=True)
    shutil.copyfile(database, short)
    if a.signing_key:
        short_sig = a.output / 'siliconforest.db.sig'
        short_sig.unlink(missing_ok=True)
        shutil.copyfile(str(database) + '.sig', short_sig)
    data['repository']['sha256'] = digest(short)
    verify_database(a.output, data)
    manifest = a.output / 'release.json'
    manifest.write_text(json.dumps(data, indent=2) + '\n')
    installer_archive(a.output / 'siliconforest.pyz')
    shutil.copyfile(ROOT / 'sources.lock.json', a.output / 'sources.lock.json')
    if a.signing_key:
        key = subprocess.check_output(['gpg', '--armor', '--export', a.signing_key])
        require(key, 'Cannot export the requested public key')
        (a.output / 'release-key.asc').write_bytes(key)
        subprocess.run(['gpg', '--batch', '--yes', '--local-user', a.signing_key,
                        '--detach-sign', str(manifest)], check=True)
        (a.output / 'install.sh').write_text(bootstrap(data['id'], a.signing_key,
                                                    digest(a.output / 'siliconforest.pyz')))
        print('Qualified signed bundle assembled locally. Nothing was published or installed.')
    else:
        print('UNSIGNED CANDIDATE: no install.sh was emitted; not an installable release.')


if __name__ == '__main__':
    main()
