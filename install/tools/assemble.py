"""Make the one-file installer: install.sh (top of the tree) = install/bootstrap.sh with the
engine's files embedded as here-documents, so the one-line command downloads exactly one file.

    python3 install/tools/assemble.py           write install.sh
    python3 install/tools/assemble.py --check   exit 1 if install.sh is not what this would write
"""
import pathlib
import sys

INSTALL = pathlib.Path(__file__).resolve().parents[1]
ROOT = INSTALL.parent
FILES = ['models.tsv'] + ['engine/%s' % n for n in ('sf_disk.py', 'sf_plan.py', 'sf_manifest.py', 'sf_kernelcfg.py',
                                                    'sf_fwslot.py', 'sf_gate.py', 'sf_engine.py')]


def assemble():
    boot = (INSTALL / 'bootstrap.sh').read_text()
    head, rest = boot.split('# @@EMBED@@', 1)
    rest = rest.split('\n}\n', 1)[1]            # drop the checkout-only sf_unpack
    out = ['# Generated by install/tools/assemble.py from install/bootstrap.sh and install/engine/: do not edit.',
           'sf_unpack() {']
    for i, rel in enumerate(FILES):
        text = (INSTALL / rel).read_text()
        tag = 'SF_EMBED_%d_END' % i
        if tag in text or not text.endswith('\n'):
            raise SystemExit('%s cannot be embedded' % rel)
        out.append("  cat > \"$1/%s\" <<'%s'" % (pathlib.Path(rel).name, tag))
        out.append(text.rstrip('\n'))
        out.append(tag)
    out.append('}')
    return head + '\n'.join(out) + '\n' + rest


def main(argv):
    text = assemble()
    target = ROOT / 'install.sh'
    if '--check' in argv:
        if not target.exists() or target.read_text() != text:
            print('install.sh is not up to date: run python3 install/tools/assemble.py')
            return 1
        print('install.sh is up to date')
        return 0
    target.write_text(text)
    target.chmod(0o755)
    print('wrote', target)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
