def source(name, syms):
    out = [HEAD % name]
    if name in METHODS:
        out.append(METHODS[name])
    strings = {k: v for k, v in syms.items() if "(" not in v}
    for k, v in syms.items():
        if k not in strings:
            out.append(v)
    if strings:
        for k in strings:
            out.append("const void *%s;" % k)
        out.append("""__attribute__((constructor)) static void make_strings(void) {
    void *cf = dlopen("/System/Library/Frameworks/CoreFoundation.framework/CoreFoundation", RTLD_LAZY);
    const void *(*make)(const void *, const char *, uint32_t) =
        cf ? (const void *(*)(const void *, const char *, uint32_t))dlsym(cf, "CFStringCreateWithCString") : 0;
    if (!make) return;""")
        for k, v in strings.items():
            out.append('    %s = make(0, "%s", 0x08000100);' % (k, v))
        out.append("}")
    return "\n".join(out) + "\n"

def main():
    out, root = sys.argv[1], sys.argv[2]
    os.makedirs(out, exist_ok=True)
    for name, (real, syms) in FILLS.items():
        c = os.path.join(out, name + ".c")
        open(c, "w").write(source(name, syms))
        o = os.path.join(out, name + ".o")
        subprocess.check_call([CC, "-O2", "-Wall", "-Werror", "-fno-stack-protector", "-isysroot", SDK, "-c", c, "-o", o])
        # Linked against the M1 copy as the system root, so ld can follow
        # the real framework's own re-exports.
        subprocess.check_call([CC, "-dynamiclib", o, "--ld-path=" + LD, "-nostdlib", "-isysroot", root,
            "-L" + root + "/usr/lib", "-lSystem",
            "-Wl,-platform_version,macos,26.5,26.5", "-Wl,-no_warn_inits",
            "-Wl,-reexport_library," + root + real,
            "-Wl,-install_name,@loader_path/sffill/%s.dylib" % name,
            "-Wl,-compatibility_version,1", "-Wl,-current_version,1",
            "-o", os.path.join(out, name + ".dylib")])
        os.remove(o)
        os.remove(c)

if __name__ == "__main__":
    main()
